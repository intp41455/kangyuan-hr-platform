function manualAggregate({ year, month, employees, punchRecords, anomalies }) {
  const { workdays: monthWorkdays } = (function () {
    let workdays = 0;
    const m = month - 1;
    const last = new Date(year, m + 1, 0);
    const total = last.getDate();
    for (let d = 1; d <= total; d++) {
      const dw = new Date(year, m, d).getDay();
      if (dw >= 1 && dw <= 5) workdays++;
    }
    return { totalDays: total, workdays };
  })();

  const empMap = new Map();
  for (const e of employees) empMap.set(String(e.id || e.employeeId), e);

  const anomaliesByEmp = new Map();
  for (const a of anomalies) {
    const k = String(a.employeeId);
    if (!anomaliesByEmp.has(k)) anomaliesByEmp.set(k, []);
    anomaliesByEmp.get(k).push(a);
  }

  const empResults = [];
  for (const e of employees) {
    const eid = String(e.id || e.employeeId);
    const list = anomaliesByEmp.get(eid) || [];
    let lateCount = 0, earlyLeaveCount = 0, missingCount = 0;
    let absentDays = 0, totalFine = 0, otHours = 0;
    const eachLeaveTypeDays = {};
    for (const lt of LEAVE_TYPES) eachLeaveTypeDays[lt.key] = 0;

    for (const a of list) {
      const t = a.type;
      if (t === ATTENDANCE_ANOMALY.LATE) lateCount++;
      else if (t === ATTENDANCE_ANOMALY.EARLY_LEAVE) earlyLeaveCount++;
      else if (t === ATTENDANCE_ANOMALY.MISSING_PUNCH) missingCount++;
      else if (t === ATTENDANCE_ANOMALY.ABSENT) absentDays += Number(a.absentDays || (a.extra && a.extra.absentDays) || 1);

      if (OT_TYPES.includes(t)) {
        otHours += Number(a.otHours || (a.extra && a.extra.otHours) || 0);
      }

      for (const lt of LEAVE_TYPES) {
        if (t === lt.anomalyType) eachLeaveTypeDays[lt.key] += 1;
      }
      totalFine += Number(a.deduction || 0);
    }

    const leaveTotal = Object.values(eachLeaveTypeDays).reduce((s, v) => s + v, 0);
    const actualAttendanceDays = Math.max(0, monthWorkdays - absentDays - leaveTotal);

    empResults.push({
      employeeId: eid,
      name: e.name || '',
      dept1: e.dept1 || e.department || '',
      dept2: e.dept2 || '',
      lateCount,
      earlyLeaveCount,
      missingCount,
      absentDays,
      totalFine,
      otHours: Number(otHours.toFixed(1)),
      eachLeaveTypeDays,
      actualAttendanceDays
    });
  }

  const deptMap = new Map();
  for (const es of empResults) {
    const k = `${es.dept1 || '未分配'}||${es.dept2 || ''}`;
    if (!deptMap.has(k)) {
      deptMap.set(k, {
        dept1: es.dept1 || '未分配',
        dept2: es.dept2 || '',
        totalEmployees: 0,
        lateCount: 0,
        earlyLeaveCount: 0,
        missingCount: 0,
        absentDays: 0,
        otTotalHours: 0,
        leaveDays: (function () { const o = {}; for (const lt of LEAVE_TYPES) o[lt.key] = 0; return o; })()
      });
    }
    const d = deptMap.get(k);
    d.totalEmployees++;
    d.lateCount += es.lateCount;
    d.earlyLeaveCount += es.earlyLeaveCount;
    d.missingCount += es.missingCount;
    d.absentDays += es.absentDays;
    d.otTotalHours += es.otHours;
    for (const lt of LEAVE_TYPES) {
      d.leaveDays[lt.key] += es.eachLeaveTypeDays[lt.key];
    }
  }

  const deptList = Array.from(deptMap.values());
  deptList.forEach(d => d.otTotalHours = Number(d.otTotalHours.toFixed(1)));

  return {
    employeeDimension: empResults,
    departmentDimension: deptList,
    monthWorkdays
  };
}

