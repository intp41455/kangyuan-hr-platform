function _seededRand(seed) {
  let s = seed;
  return function () {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
}

function makeTime(dateStr, hh, mm) {
  const d = new Date(dateStr);
  d.setHours(hh, mm, 0, 0);
  return d;
}

function _getAug2026Workdays() {
  const workdays = [];
  for (let d = 1; d <= 31; d++) {
    const date = new Date(2026, 7, d);
    const day = date.getDay();
    if (day >= 1 && day <= 5) {
      const mm = String(d).padStart(2, '0');
      workdays.push(`2026-08-${mm}`);
    }
  }
  return workdays;
}

